/**
 * Assembles the whole lab family into one static site in dist/:
 *   dist/            ← this repo's web/ (the hub page)
 *   dist/<repo>/     ← each lab repo's web/ (its interactive lab)
 * One site means one Cloudflare Pages project, so no lab depends on owning a
 * globally unique <repo>.pages.dev name, and every lab shares one origin
 * (the hub reads their progress from the same localStorage).
 *
 * Lab sources: a sibling checkout (../<repo>) if present, otherwise a shallow
 * clone into .cache/. Set LABS_REMOTE=1 to always clone from GitHub.
 */
import { cp, mkdir, rm, writeFile, access } from "node:fs/promises";
import { execFileSync } from "node:child_process";
import { fileURLToPath } from "node:url";
import { dirname, join, basename } from "node:path";

const ROOT = dirname(dirname(fileURLToPath(import.meta.url)));
const DIST = join(ROOT, "dist");
const CACHE = join(ROOT, ".cache");
const OWNER = "swapnull-in";
const REPOS = ["messaging-queues", "databases", "caching", "realtime-delivery", "search-and-ranking",
               "blob-storage-cdn", "stream-processing", "geospatial", "rate-limiting", "distributed-systems"];

// Dev-only server and per-site header files don't belong in the published tree.
const SKIP = new Set(["serve.mjs", "_headers"]);
const publishable = (src) => !SKIP.has(basename(src));
const exists = (p) => access(p).then(() => true, () => false);

async function labWebDir(repo) {
  const sibling = join(ROOT, "..", repo, "web");
  if (!process.env.LABS_REMOTE && await exists(sibling)) return sibling;
  const dir = join(CACHE, repo);
  await rm(dir, { recursive: true, force: true });
  execFileSync("git", ["clone", "--quiet", "--depth", "1", `https://github.com/${OWNER}/${repo}.git`, dir], { stdio: "inherit" });
  return join(dir, "web");
}

await rm(DIST, { recursive: true, force: true });
await mkdir(DIST, { recursive: true });
await cp(join(ROOT, "web"), DIST, { recursive: true, filter: publishable });

for (const repo of REPOS) {
  const src = await labWebDir(repo);
  await cp(src, join(DIST, repo), { recursive: true, filter: publishable });
  console.log(`  ${repo.padEnd(20)} ← ${src.startsWith(CACHE) ? "github" : "sibling checkout"}`);
}

// Cloudflare Pages headers for the combined tree (hub fonts + each lab's fonts).
await writeFile(join(DIST, "_headers"), `# Generated by scripts/build.mjs
# Fonts are content-hashed and never change — cache them hard.
/fonts/*
  Cache-Control: public, max-age=31536000, immutable
/*/fonts/*
  Cache-Control: public, max-age=31536000, immutable
# Always revalidate the HTML so edits show up immediately.
/*
  Cache-Control: public, max-age=0, must-revalidate
  X-Content-Type-Options: nosniff
`);
console.log(`\n  built ${DIST}\n`);
